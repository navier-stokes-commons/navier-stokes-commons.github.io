      pauseBtn = controls.querySelector('[data-r17-pause]');
      resetBtn = controls.querySelector('[data-r17-reset]');
      modeBtns = [...controls.querySelectorAll('[data-r17-mode]')];

      status = document.createElement('div');
      status.className = 'r17-status';
